#!/usr/bin/env python3
"""Integration-test the exact SQL schema shipped in src/search-index.js.
Uses SQLite's bundled FTS5 locally; does not touch Cloudflare quotas.
"""
import json
import sqlite3
import subprocess

raw=subprocess.check_output([
    "node","--input-type=module","-e",
    'import {VIRTUAL_SQL,TRIGGERS} from "./src/search-index.js";'
    'process.stdout.write(JSON.stringify({virtual:VIRTUAL_SQL,triggers:TRIGGERS}));'
],text=True)
ddl=json.loads(raw)
db=sqlite3.connect(":memory:")
db.executescript("""
CREATE TABLE speeches (
 id TEXT PRIMARY KEY, meeting_id TEXT, idx INTEGER, speaker TEXT,
 clock TEXT, content TEXT, page INTEGER
);
INSERT INTO speeches VALUES('s1','m',0,'Mette Thiesen','13:00','En ulv er ikke en problemulv.',1);
INSERT INTO speeches VALUES('s2','m',1,'En minister','13:02','Det er bare pulver.',1);
INSERT INTO speeches VALUES('s3','m',2,'Mette Thiesen','13:05','Problemulven er her.',1);
""")
db.execute(ddl["virtual"])
for trigger in ddl["triggers"]:
    db.execute(trigger)
db.execute("INSERT INTO speech_fts(speech_fts) VALUES('rebuild')")
def hits(query):
    return [r[0] for r in db.execute(
        "WITH hits AS MATERIALIZED (SELECT rowid FROM speech_fts WHERE speech_fts MATCH ? LIMIT 1000) "
        "SELECT s.id FROM hits JOIN speeches s ON s.rowid=hits.rowid ORDER BY s.idx",
        (query,)
    )]
assert hits('content:"ulv"')==["s1"],hits('content:"ulv"')
assert hits('content:"problemulv"')==["s1"],hits('content:"problemulv"')
assert hits('speaker:"mette"*')==["s1","s3"],hits('speaker:"mette"*')
assert hits('content:"pulver"')==["s2"]
db.execute("INSERT INTO speeches VALUES('s4','m',3,'Mette Thiesen','13:06','Ulven er væk.',1)")
assert hits('content:"ulven"')==["s4"]
db.execute("UPDATE speeches SET content='Ren isvinter.' WHERE id='s4'")
assert hits('content:"ulven"')==[]
db.execute("DELETE FROM speeches WHERE id='s1'")
assert hits('content:"ulv"')==[]
assert hits('content:"problemulv"')==[]
# Verify the exact SQL generated by findSpeeches, including the correlated
# next-later-clock lookup (same-clock fragments are not a new speech interval).
live_query=json.loads(subprocess.check_output([
    "node","--input-type=module","-e",
    """
import {findSpeeches} from './src/worker.js';
let last={};
const db={prepare(sql){return {
  bind(...args){last={sql,args};return this;},
  async first(){return {value:'1'};},
  async all(){return {results:[]};}
};}};
await findSpeeches({DB:db},new URLSearchParams({q:'problemulv'}));
process.stdout.write(JSON.stringify(last));
"""
],text=True))
db.executescript("""
ALTER TABLE speeches ADD COLUMN party TEXT;
CREATE TABLE meetings (
  id TEXT PRIMARY KEY,date TEXT,status TEXT,samling TEXT,
  meeting_no INTEGER,title TEXT,source_url TEXT
);
CREATE TABLE meeting_audio (
  meeting_id TEXT PRIMARY KEY,mp3_url TEXT,title TEXT,verified_at TEXT
);
CREATE TABLE favorites (speech_id TEXT PRIMARY KEY, added_at TEXT);
INSERT INTO meetings VALUES ('m','2026-08-26','ready','20252',19,'Møde 19','https://ft.dk');
INSERT INTO meeting_audio VALUES ('m','https://example.org/original.mp3','Salen','2026-08-26');
INSERT INTO speeches (id,meeting_id,idx,speaker,clock,content,page,party)
 VALUES ('s5','m',4,'Christian Rabjerg Madsen','14:17:20','Vi oplever en problemulv.',1,'S');
INSERT INTO speeches (id,meeting_id,idx,speaker,clock,content,page,party)
 VALUES ('s6','m',5,'Karsten Hønge','14:17:20','Jeg spørger lige igen.',1,'SF');
INSERT INTO speeches (id,meeting_id,idx,speaker,clock,content,page,party)
 VALUES ('s7','m',6,'Karsten Hønge','14:17:59','Næste indlæg.',1,'SF');
""")
query=live_query["sql"]
args=live_query["args"]
assert "next_clock" in query and "sx.idx>s.idx" in query
rows=db.execute(query,args).fetchall()
assert len(rows)==1,rows
columns=[x[0] for x in db.execute(query,args).description]
record=dict(zip(columns,rows[0]))
assert record["id"]=="s5",record
assert record["next_clock"]=="14:17:59",record

print("OK: actual FTS5 SQL, whole-word matching, incremental insert/update/delete.")
print('OK: actual search SQL returns the next distinct speech timestamp.')
